/// <summary>
/// Specifies the direction for sorting operations.
/// </summary>
public enum SortDirectionType
{
    /// <summary>
    /// Sort in ascending order (A to Z, 0 to 9).
    /// </summary>
    Asc,

    /// <summary>
    /// Sort in descending order (Z to A, 9 to 0).
    /// </summary>
    Desc,
}